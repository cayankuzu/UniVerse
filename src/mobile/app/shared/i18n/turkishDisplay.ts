export function formatTurkishDisplayText(value: string) {
  const trimmed = String(value || "").trim();
  if (!trimmed) return "";

  let next = trimmed;
  for (const [source, replacement] of Object.entries(PHRASE_OVERRIDES)) {
    next = next.replaceAll(source, replacement);
  }

  return next
    .split(" ")
    .map((word) => WORD_OVERRIDES[word] || word)
    .join(" ");
}
